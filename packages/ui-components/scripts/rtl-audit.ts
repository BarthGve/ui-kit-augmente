// ---------------------------------------------------------------------------
// Lists the component stylesheets that use physical CSS properties (left,
// right, margin-left, text-align: left...), which do not mirror in a
// right-to-left layout. The logical equivalents are inline-start / inline-end.
//
// This is a report, not a gate: fixes are separate stories.
//
// Run it with:
//      yarn tsx scripts/rtl-audit.ts > ../../docs/rtl-audit.md
// ---------------------------------------------------------------------------

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const COMPONENTS = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/components",
);

const PHYSICAL =
  /(^|[\s{;])(left|right|margin-left|margin-right|padding-left|padding-right|border-left[\w-]*|border-right[\w-]*|border-(top|bottom)-(left|right)-radius|float|text-align)\s*:\s*([^;]*)/;
// `text-align` and `float` are physical only with left / right.
const isPhysical = (property: string, value: string) =>
  !/^(text-align|float)$/.test(property) || /\b(left|right)\b/.test(value);

const walk = (dir: string): string[] =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.name.endsWith(".scss") ? [full] : [];
  });

type Finding = { file: string; line: number; text: string };
const findings: Finding[] = [];

for (const file of walk(COMPONENTS)) {
  fs.readFileSync(file, "utf8")
    .split("\n")
    .forEach((text, index) => {
      const code = text.replace(/\/\/.*$/, "");
      const match = code.match(PHYSICAL);
      if (match && isPhysical(match[2], match[5])) {
        findings.push({
          file: path.relative(COMPONENTS, file),
          line: index + 1,
          text: code.trim(),
        });
      }
    });
}

const byComponent = new Map<string, Finding[]>();
for (const finding of findings) {
  const component = finding.file.split(path.sep)[0];
  byComponent.set(component, [...(byComponent.get(component) ?? []), finding]);
}

const rows = [...byComponent.entries()].sort((a, b) => b[1].length - a[1].length);

console.log("# Right-to-left audit\n");
console.log(
  "Component stylesheets that use physical CSS properties, which do not mirror when the reading direction is right to left. Replace them with logical ones (`margin-inline-start`, `padding-inline-end`, `inset-inline-start`, `text-align: start`, `border-start-start-radius`...). Generated by `scripts/rtl-audit.ts`; fixes are separate stories.\n",
);
console.log(`**${findings.length} occurrences in ${rows.length} components.**\n`);
console.log("| Component | Occurrences |\n| --- | ---: |");
rows.forEach(([component, list]) => console.log(`| \`${component}\` | ${list.length} |`));
console.log("\n## Details\n");
rows.forEach(([component, list]) => {
  console.log(`### \`${component}\`\n`);
  list.forEach((f) => console.log(`- \`${f.file}:${f.line}\` — \`${f.text}\``));
  console.log("");
});
